const {readFileSync}=require('fs');
const assert=require('assert/strict');
(async()=>{
 const {pickName,createNameIndex,mountDigitalHover}=await import('data:text/javascript;base64,'+readFileSync('geometry-campus/digital-hover.js').toString('base64'));
 const square=(a,b,c,d)=>[[a,b],[c,b],[c,d],[a,d],[a,b]];
 const building={name:'楼',type:'建筑',polys:[[square(0,0,20,20),square(5,5,10,10)]]};
 const road={name:'路',type:'道路',coords:[[30,0],[30,30]]};
 const lake={name:'湖',type:'景观',polys:[[square(-20,-20,40,40)]]};
 assert.equal(pickName([lake,building],2,2,1).name,'楼');
 assert.equal(pickName([building],7,7,1),null,'polygon holes');
 assert.equal(pickName([road,lake],34,4,1).name,'路');
 assert.equal(pickName([road],34,4,2),null,'screen pixel tolerance');
 assert.equal(pickName([road],30,5,.1).name,'路');
 assert.equal(pickName([{name:'雕像',point:[2,2]},building],2,2,1).name,'雕像');
 const data={features:[{properties:{osm_id:1,name:'新楼名'},geometry:{type:'Polygon'}},{properties:{name:'雕像'},geometry:{type:'Point',coordinates:[1,2]}}]};
 const index=createNameIndex(data,[{osm_id:1,name:'旧楼名',building:'yes',polys:building.polys},{kind:'campus',name:'校园',polys:lake.polys},{polys:lake.polys}],p=>p);
 assert.equal(index.length,2);assert.equal(index[0].name,'新楼名');
 const events=()=>({handlers:{},addEventListener(k,fn){(this.handlers[k]??=[]).push(fn)},emit(k,e={}){for(const fn of this.handlers[k]||[])fn(e)}});
 const canvas=Object.assign(events(),{width:100,height:100,getBoundingClientRect:()=>({left:0,top:0,width:100,height:100})});
 let tip;global.document=Object.assign(events(),{createElement:()=>({style:{},offsetWidth:50,offsetHeight:30}),body:{append(t){tip=t}}});
 global.window=events();global.innerWidth=100;global.innerHeight=100;
 const state={digital:true,zoom:1,camera:{x:0,y:0}};
 const hover=mountDigitalHover(canvas,[building],()=>state);hover.sync();
 const pointer={pointerId:1,pointerType:'mouse',clientX:52,clientY:52,buttons:0};
 canvas.emit('pointermove',pointer);assert.equal(tip.textContent,'楼');assert.equal(tip.hidden,false);
 canvas.emit('pointerdown',pointer);assert.equal(tip.hidden,true);
 canvas.emit('pointermove',{...pointer,clientX:65});canvas.emit('pointerup',pointer);assert.equal(tip.hidden,true,'drag does not become tap');
 canvas.emit('pointerdown',{...pointer,pointerType:'touch'});canvas.emit('pointerup',{...pointer,pointerType:'touch'});assert.equal(tip.hidden,false,'touch tap');
 state.zoom=2;hover.sync();assert.equal(tip.hidden,true,'zoom clears stale tooltip');
 state.digital=false;canvas.emit('pointermove',pointer);assert.equal(tip.hidden,true,'panorama disabled');
 console.log('PASS: DOM event harness hover, drag, tap, zoom, mode switching');
 console.log('PASS: buildings, polygon holes, road tolerance across zoom, POI priority, name overrides, unnamed/boundary exclusion');
})();
